feed(Buffer.from(ENGLISH.repeat(6), 'latin1'));
feed(Buffer.from(CODE.repeat(6), 'latin1'));

// --- the repo's own source (MIT): a broad, licence-clean code+prose corpus. ---
let used = 0;
const BUDGET = 3_000_000;
(function walk(dir) {
  if (used > BUDGET) return;
  for (const name of readdirSync(dir)) {
    if (['node_modules', '.git', 'dist'].includes(name)) continue;
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) walk(p);
    else if (
      (name.endsWith('.ts') || name.endsWith('.md')) &&
      !name.endsWith('_symbol-bigram.ts') &&
      used < BUDGET
    ) {
      feed(readFileSync(p));
      used += st.size;
    }
  }
})(join(ROOT, 'src'));

// Row-normalised log-probabilities with add-1 smoothing, quantised to int8 at 1/SCALE nats.
const SCALE = 16;
const quant = new Int8Array(S * S);
for (let p = 0; p < S; p++) {
  let row = 0;
  for (let c = 0; c < S; c++) row += counts[p * S + c] + 1;
  for (let c = 0; c < S; c++) {
    const lp = Math.log((counts[p * S + c] + 1) / row); // negative
    quant[p * S + c] = Math.max(-128, Math.round(lp * SCALE));
  }
}

const b64 = Buffer.from(quant.buffer).toString('base64');
const alphaLiteral = JSON.stringify(ALPHA);
const out = `// GENERATED by scripts/gen-symbol-bigram.mjs — do not edit by hand.
// Character-bigram log-probabilities over printable ASCII (+ tab/LF/CR), trained on original English
// and code samples plus this repo's own MIT source. Used to rank candidate symbol-word decodings.
/** Byte values of the alphabet; index in this array is the symbol id. Other bytes use the OTHER id. */
export const BIGRAM_ALPHA: readonly number[] = ${alphaLiteral};
/** Symbols in the alphabet; the OTHER bucket is id ${SYMS}. */
export const BIGRAM_SYMS = ${SYMS};
/** Quantisation: stored value / BIGRAM_SCALE = log-probability in nats. */
export const BIGRAM_SCALE = ${SCALE};
/** (BIGRAM_SYMS+1)^2 int8 values, row-major [prev][cur], base64 of the Int8Array. */
export const BIGRAM_B64 =
  '${b64}';
`;
writeFileSync(join(ROOT, 'src/tools/crypto/_symbol-bigram.ts'), out);
console.log(
  `wrote _symbol-bigram.ts: ${SYMS} symbols, repo corpus ${used} bytes, table ${quant.length} int8 (${b64.length} b64 chars)`,
);
